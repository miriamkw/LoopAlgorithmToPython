def load_test_data():
    """Load and parse the test JSON data file."""
    test_file = Path(__file__).parent.parent / "python_tests/test_files/generate_prediction_input.json"
    
    try:
        with open(test_file, 'r') as f:
            data = json.load(f)
        print(f"✓ Successfully loaded test data from {test_file}")
        return data
    except FileNotFoundError:
        raise FileNotFoundError(f"Test data file not found: {test_file}")
    except json.JSONDecodeError as e:
        raise ValueError(f"Invalid JSON in test file: {e}")

def parse_glucose_history(data):
    """Extract and parse historical glucose data for baseline context."""
    glucose_history = data.get('glucoseHistory', [])
    
    if not glucose_history:
        print("⚠ No glucose history found in test data")
        return pd.DataFrame()
    
    # Convert to DataFrame
    glucose_df = pd.DataFrame(glucose_history)
    glucose_df['datetime'] = pd.to_datetime(glucose_df['date'])
    glucose_df = glucose_df.sort_values('datetime')
    
    print(f"✓ Parsed {len(glucose_df)} glucose history points")
    print(f"  Date range: {glucose_df['datetime'].min()} to {glucose_df['datetime'].max()}")
    print(f"  Glucose range: {glucose_df['value'].min()}-{glucose_df['value'].max()} mg/dL")
    
    return glucose_df

def extract_carb_insulin_events(data):
    """Extract carbohydrate and insulin events for annotation."""
    # Extract carb entries
    carb_events = []
    for entry in data.get('carbEntries', []):
        carb_events.append({
            'datetime': pd.to_datetime(entry['date']),
            'grams': entry['grams'],
            'type': 'carbs'
        })
    
    # Extract insulin doses
    insulin_events = []
    for dose in data.get('doses', []):
        if dose['type'] == 'bolus' and dose['volume'] > 0:
            insulin_events.append({
                'datetime': pd.to_datetime(dose['startDate']),
                'volume': dose['volume'],
                'type': 'bolus'
            })
    
    print(f"✓ Found {len(carb_events)} carb entries and {len(insulin_events)} bolus doses")
    return carb_events, insulin_events

def generate_all_predictions(test_data):
    """Generate predictions using all 5 prediction methods."""
    print("\n🔄 Generating predictions...")
    
    predictions = {}
    
    try:
        # Generate all predictions
        print("  📊 All effects (baseline)...")
        all_values, all_dates = api.get_prediction_values_and_dates(test_data)
        predictions['all'] = {'values': all_values, 'dates': all_dates}
        
        print("  💉 Insulin effects only...")
        insulin_values, insulin_dates = api.get_insulin_prediction_values_and_dates(test_data)
        predictions['insulin'] = {'values': insulin_values, 'dates': insulin_dates}
        
        print("  🍞 Carbohydrate effects only...")
        carbs_values, carbs_dates = api.get_carbs_prediction_values_and_dates(test_data)
        predictions['carbs'] = {'values': carbs_values, 'dates': carbs_dates}
        
        print("  📈 Momentum effects only...")
        momentum_values, momentum_dates = api.get_momentum_prediction_values_and_dates(test_data)
        predictions['momentum'] = {'values': momentum_values, 'dates': momentum_dates}
        
        print("  🔄 Retrospective correction only...")
        retro_values, retro_dates = api.get_retrospection_prediction_values_and_dates(test_data)
        predictions['retrospection'] = {'values': retro_values, 'dates': retro_dates}
        
        print("✓ All predictions generated successfully")
        
    except Exception as e:
        print(f"❌ Error generating predictions: {e}")
        raise
    
    return predictions

def convert_dates_to_datetime(predictions):
    """Convert date strings to datetime objects for all predictions."""
    for effect_type, data in predictions.items():
        dates_dt = [pd.to_datetime(date) for date in data['dates']]
        data['dates_dt'] = dates_dt
        print(f"  ✓ {effect_type}: {len(dates_dt)} prediction points")
    
    return predictions

def create_main_trajectory_plot(predictions, glucose_history, carb_events, insulin_events):
    """Create the main trajectory plot showing all prediction curves."""
    print("\n🎨 Creating main trajectory plot...")
    
    fig, ax = plt.subplots(figsize=(14, 8))
    
    # Define colors for each prediction type
    colors = {
        'all': '#2E86AB',           # Blue - comprehensive prediction
        'insulin': '#A23B72',       # Purple - insulin effect  
        'carbs': '#F18F01',         # Orange - carb effect
        'momentum': '#C73E1D',      # Red - momentum effect
        'retrospection': '#6A994E'  # Green - retrospective correction
    }
    
    # Define line styles for differentiation
    styles = {
        'all': '-',           # Solid line for main prediction
        'insulin': '--',      # Dashed
        'carbs': '-.',        # Dash-dot
        'momentum': ':',      # Dotted
        'retrospection': '-'  # Solid
    }
    
    # Plot historical glucose data as baseline context
    if not glucose_history.empty:
        ax.plot(glucose_history['datetime'], glucose_history['value'], 
               'o-', color='gray', linewidth=2, markersize=4, alpha=0.7,
               label='Historical Glucose', zorder=1)
    
    # Plot all prediction curves
    for effect_type, data in predictions.items():
        label_map = {
            'all': 'All Effects (Baseline)',
            'insulin': 'Insulin Only',
            'carbs': 'Carbohydrates Only', 
            'momentum': 'Glucose Momentum Only',
            'retrospection': 'Retrospective Correction Only'
        }
        
        ax.plot(data['dates_dt'], data['values'], 
               color=colors[effect_type], 
               linestyle=styles[effect_type],
               linewidth=2.5 if effect_type == 'all' else 2,
               alpha=0.9 if effect_type == 'all' else 0.7,
               label=label_map[effect_type],
               zorder=3 if effect_type == 'all' else 2)
    
    # Add carb and insulin event annotations
    y_min, y_max = ax.get_ylim()
    annotation_height = y_max + (y_max - y_min) * 0.05
    
    # Annotate carb entries
    for carb in carb_events:
        ax.annotate(f'{carb["grams"]}g', 
                   xy=(carb['datetime'], annotation_height),
                   xytext=(carb['datetime'], annotation_height + (y_max - y_min) * 0.08),
                   ha='center', va='bottom', fontsize=8,
                   arrowprops=dict(arrowstyle='->', color='orange', lw=1),
                   bbox=dict(boxstyle='round,pad=0.2', facecolor='orange', alpha=0.7))
    
    # Annotate insulin boluses
    for bolus in insulin_events:
        ax.annotate(f'{bolus["volume"]:.2f}U', 
                   xy=(bolus['datetime'], y_min - (y_max - y_min) * 0.05),
                   xytext=(bolus['datetime'], y_min - (y_max - y_min) * 0.12),
                   ha='center', va='top', fontsize=8,
                   arrowprops=dict(arrowstyle='->', color='purple', lw=1),
                   bbox=dict(boxstyle='round,pad=0.2', facecolor='purple', alpha=0.7))
    
    # Formatting
    ax.set_xlabel('Time', fontsize=12, fontweight='bold')
    ax.set_ylabel('Glucose (mg/dL)', fontsize=12, fontweight='bold')
    ax.set_title('Glucose Prediction Trajectories by Algorithm Effects\n' +
                'Comparing Individual vs. Combined Algorithm Components', 
                fontsize=14, fontweight='bold', pad=20)
    
    # Format x-axis to show dates nicely
    ax.xaxis.set_major_formatter(mdates.DateFormatter('%m/%d %H:%M'))
    ax.xaxis.set_major_locator(mdates.HourLocator(interval=4))
    plt.setp(ax.xaxis.get_majorticklabels(), rotation=45, ha='right')
    
    # Add grid and legend
    ax.grid(True, alpha=0.3, linestyle='--')
    ax.legend(loc='upper right', frameon=True, fancybox=True, shadow=True)
    
    # Set reasonable y-axis limits
    all_values = [val for pred in predictions.values() for val in pred['values']]
    if not glucose_history.empty:
        all_values.extend(glucose_history['value'].tolist())
    
    y_min_data = min(all_values)
    y_max_data = max(all_values)
    margin = (y_max_data - y_min_data) * 0.2
    ax.set_ylim(y_min_data - margin, y_max_data + margin)
    
    plt.tight_layout()
    return fig, ax

def create_effects_comparison_subplots(predictions, glucose_history):
    """Create individual subplot comparisons for each effect type."""
    print("🎨 Creating effects comparison subplots...")
    
    fig, axes = plt.subplots(2, 2, figsize=(16, 12))
    axes = axes.flatten()
    
    effect_types = ['insulin', 'carbs', 'momentum', 'retrospection']
    titles = [
        'Insulin Effect vs. All Effects',
        'Carbohydrate Effect vs. All Effects', 
        'Glucose Momentum vs. All Effects',
        'Retrospective Correction vs. All Effects'
    ]
    
    colors = ['#A23B72', '#F18F01', '#C73E1D', '#6A994E']
    
    for i, (effect_type, title, color) in enumerate(zip(effect_types, titles, colors)):
        ax = axes[i]
        
        # Plot baseline (all effects) in gray
        ax.plot(predictions['all']['dates_dt'], predictions['all']['values'], 
               color='gray', linewidth=2, alpha=0.7, label='All Effects', linestyle='-')
        
        # Plot individual effect in color
        ax.plot(predictions[effect_type]['dates_dt'], predictions[effect_type]['values'], 
               color=color, linewidth=2.5, alpha=0.9, label=f'{effect_type.capitalize()} Only')
        
        # Add historical glucose context if available
        if not glucose_history.empty:
            ax.plot(glucose_history['datetime'], glucose_history['value'], 
                   'o', color='lightgray', markersize=3, alpha=0.5, label='Historical')
        
        # Formatting
        ax.set_title(title, fontsize=11, fontweight='bold')
        ax.set_ylabel('Glucose (mg/dL)', fontsize=10)
        ax.grid(True, alpha=0.3)
        ax.legend(fontsize=9)
        
        # Format x-axis
        ax.xaxis.set_major_formatter(mdates.DateFormatter('%m/%d %H:%M'))
        ax.xaxis.set_major_locator(mdates.HourLocator(interval=6))
        plt.setp(ax.xaxis.get_majorticklabels(), rotation=45, ha='right', fontsize=8)
    
    plt.suptitle('Individual Algorithm Effects Comparison', fontsize=16, fontweight='bold', y=0.98)
    plt.tight_layout()
    return fig, axes

def calculate_prediction_statistics(predictions):
    """Calculate and display summary statistics for all predictions."""
    print("\n📊 Calculating prediction statistics...")
    
    stats = {}
    
    for effect_type, data in predictions.items():
        values = np.array(data['values'])
        
        stats[effect_type] = {
            'min': np.min(values),
            'max': np.max(values),
            'mean': np.mean(values),
            'std': np.std(values),
            'range': np.max(values) - np.min(values),
            'final': values[-1] if len(values) > 0 else 0.0
        }
    
    return stats

def print_summary_statistics(stats):
    """Print formatted summary statistics to console."""
    print("\n" + "="*80)
    print("📋 PREDICTION SUMMARY STATISTICS")
    print("="*80)
    
    # Create a formatted table
    headers = ['Effect Type', 'Min', 'Max', 'Mean', 'Std Dev', 'Range', 'Final']
    
    print(f"{'Effect Type':<20} {'Min':<8} {'Max':<8} {'Mean':<8} {'Std':<8} {'Range':<8} {'Final':<8}")
    print("-" * 80)
    
    effect_names = {
        'all': 'All Effects',
        'insulin': 'Insulin Only', 
        'carbs': 'Carbs Only',
        'momentum': 'Momentum Only',
        'retrospection': 'Retrospection Only'
    }
    
    for effect_type in ['all', 'insulin', 'carbs', 'momentum', 'retrospection']:
        if effect_type in stats:
            s = stats[effect_type]
            print(f"{effect_names[effect_type]:<20} {s['min']:<8.1f} {s['max']:<8.1f} " +
                  f"{s['mean']:<8.1f} {s['std']:<8.1f} {s['range']:<8.1f} {s['final']:<8.1f}")
    
    print("\n💡 Key Insights:")
    
    # Compare ranges
    all_range = stats['all']['range']
    for effect_type in ['insulin', 'carbs', 'momentum', 'retrospection']:
        if effect_type in stats:
            effect_range = stats[effect_type]['range']
            percentage = (effect_range / all_range * 100) if all_range > 0 else 0
            print(f"   • {effect_names[effect_type]} shows {percentage:.1f}% of the glucose variability seen in combined effects")
    
    # Highlight dominant effects
    max_range_effect = max(
        [k for k in ['insulin', 'carbs', 'momentum', 'retrospection'] if k in stats],
        key=lambda x: stats[x]['range']
    )
    print(f"   • {effect_names[max_range_effect]} has the largest individual impact on glucose predictions")

